/// TRIAL (decision 0022, not yet written): the OwnCoffer server running
/// inside the Windows or Android app, on a SQLite file, for one person on
/// one device. Same endpoints, same engine as the Docker server.
///
/// [dataDir] is the app's private folder: it receives the secrets
/// (config/passwords.yaml, created once), the migrations ([migrations],
/// copied at each start) and the database file.
Future<({Serverpod pod, Uri api})> startEmbedded({
  required Directory dataDir,
  required Map<String, String> migrations,
}) async {
  await dataDir.create(recursive: true);
  final config = Directory('${dataDir.path}/config')..createSync();
  final passwords = File('${config.path}/passwords.yaml');
  if (!passwords.existsSync()) {
    final random = Random.secure();
    String secret() =>
        base64Url.encode(List<int>.generate(32, (_) => random.nextInt(256)));
    passwords.writeAsStringSync('''
shared:
  serviceSecret: '${secret()}'
  emailSecretHashPepper: '${secret()}'
  jwtHmacSha512PrivateKey: '${secret()}'
  jwtRefreshTokenHashPepper: '${secret()}'
''');
  }
  // The SQLite migrations, generated by `serverpod create-migration` in the
  // standalone project and shipped with the app.
  for (final e in migrations.entries) {
    final f = File('${dataDir.path}/migrations/${e.key}');
    await f.parent.create(recursive: true);
    await f.writeAsString(e.value);
  }

  final pod = Serverpod(
    const ['--apply-migrations'],
    serverDirectory: dataDir,
    config: ServerpodConfig(
      runMode: 'production',
      // Port 0: the system picks a free one at each start.
      apiServer: ServerConfig(
        port: 0,
        publicHost: '127.0.0.1',
        publicPort: 0,
        publicScheme: 'http',
      ),
      database: SqliteDatabaseConfig(
        filePath: '${dataDir.path}/owncoffer.db',
      ),
      applyMigrations: true,
      // SQLite allows one writer: no session log in the database.
      sessionLogs: SessionLogConfig.buildDefault(
        databaseEnabled: false,
        runMode: 'production',
      ),
    ),
  );
  pod.initializeAuthServices(
    tokenManagerBuilders: [JwtConfigFromPasswords()],
    identityProviderBuilders: [buildEmailIdpConfig()],
  );
  // Serverpod listens on every interface: only this device may talk to it.
  pod.server.addMiddleware((Handler next) {
    return (Request req) async {
      if (!isLocalAddress(req.connectionInfo.remote.address.toString())) {
        return Response.forbidden(body: Body.fromString('local_only'));
      }
      return next(req);
    };
  });
  await pod.start();
  final port = pod.server.port;
  return (pod: pod, api: Uri.parse('http://127.0.0.1:$port/'));
}

/// This device only: 127.0.0.1, ::1, and 127.0.0.1 seen through an IPv6
/// socket (::ffff:127.0.0.1), as on any machine with IPv6.
bool isLocalAddress(String address) {
  var a = address.trim().toLowerCase();
  if (a.startsWith('::ffff:')) a = a.substring(7);
  final ip = InternetAddress.tryParse(a);
  return ip != null && ip.isLoopback;
}
