import 'dart:convert';
import 'dart:io';

/// Writes the SQLite migrations into a Dart file, so that the Windows and
/// Android apps carry them (decision 0022). Run by tool/standalone.sh.
///
///     dart run tool/embed_migrations.dart MIGRATIONS_DIR OUTPUT.dart
void main(List<String> args) {
  final dir = Directory(args[0]);
  // Everything: the server checks the definitions when it migrates.
  final files = dir.listSync(recursive: true).whereType<File>().toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/standalone.sh migrations: do not edit.')
    ..writeln('// The SQLite schema of the standalone version (decision 0022).')
    ..writeln()
    ..writeln('/// Path under migrations/ → content.')
    ..writeln('const sqliteMigrations = <String, String>{');
  for (final f in files) {
    final rel = f.path.substring(dir.path.length + 1).replaceAll(r'\', '/');
    out.writeln('  ${jsonEncode(rel)}: ${_literal(f.readAsStringSync())},');
  }
  out.writeln('};');
  File(args[1])
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
}

/// A Dart string literal: JSON escaping is valid Dart, with `$` escaped.
String _literal(String s) => jsonEncode(s).replaceAll(r'$', r'\$');
